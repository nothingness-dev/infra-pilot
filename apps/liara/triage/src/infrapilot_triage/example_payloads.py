"""Explicit, offline MOCK fixture generation using real models, engine, and gate.

This module is never installed as an HTTP identity provider. Importing it does
not construct a mock identity or write files. The CLI requires --mock.
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
from typing import Any

from pydantic import TypeAdapter

from .api_contracts import AuthorizationRequest
from .approval_integration import ApprovalIntegration
from .approval_store import InMemoryApprovalStore
from .approvals import GateDecision
from .authorization import ApprovalGate
from .engine import diagnose
from .identity import AuthenticatedActor, Permission
from .policy import ActionIntent, ActionPolicy, ActionType, CanonicalAction
from .redaction import sanitize_snapshot
from .schemas import LogEntry, ServiceSnapshot


class _MockIdentityBoundary:
    """One offline, preinstalled opaque session; no HTTP credential mechanism."""

    def __init__(self) -> None:
        self.session = object()
        self.actor = AuthenticatedActor("MOCK-requester")

    def authenticate(self, authentication: object) -> AuthenticatedActor | None:
        return self.actor if authentication is self.session else None

    def is_authorized(self, actor: AuthenticatedActor, action: CanonicalAction, permission: Permission) -> bool:
        return (
            actor == self.actor and action.service_id == "MOCK-service"
            and action.action_type == ActionType.RESTART_SERVICE
            and permission in (Permission.REQUEST, Permission.EXECUTE)
        )


def build_mock_examples(*, mock: bool) -> dict[str, Any]:
    """Return five request/response pairs. Explicit mock=True is mandatory.

    Pending approval IDs are genuinely generated by the gate and vary per run.
    Nothing is executed, no approval is granted, and no external system is used.
    """
    if mock is not True:
        raise ValueError("Explicit MOCK mode is required")
    examples: dict[str, Any] = {}
    snapshots = {
        "mock_db_http500": ServiceSnapshot(
            service_id="MOCK-service", status="unhealthy", data_source="mock", http_status=500,
            logs=[LogEntry(message="PostgreSQL connection refused", level="error")],
        ),
        "mock_cpu_latency": ServiceSnapshot(
            service_id="MOCK-service", status="degraded", data_source="mock",
            cpu_usage_percent=97, response_time_ms=2400,
        ),
        "mock_healthy_incomplete": ServiceSnapshot(
            service_id="MOCK-service", status="healthy", data_source="mock",
        ),
    }
    for name, snapshot in snapshots.items():
        sanitized, _changed = sanitize_snapshot(snapshot)
        examples[f"{name}.request.json"] = snapshot.model_dump(mode="json")
        examples[f"{name}.response.json"] = diagnose(sanitized).model_dump(mode="json")

    identity = _MockIdentityBoundary()
    policy = ActionPolicy()
    gate = ApprovalGate(
        identity=identity, policy=policy, store=InMemoryApprovalStore(),
        clock=lambda: datetime(2026, 1, 1, tzinfo=timezone.utc),
    )
    intent = ActionIntent(service_id="MOCK-service", action_type="restart_service")
    decision_adapter = TypeAdapter(GateDecision)
    pending = gate.request_approval(intent, authentication=identity.session)
    examples["mock_sensitive_pending.request.json"] = intent.model_dump(mode="json")
    examples["mock_sensitive_pending.response.json"] = decision_adapter.dump_python(pending, mode="json")
    denied = ApprovalIntegration(policy=policy, gate=gate).authorize(intent, authentication=None)
    examples["mock_authorization_denied.request.json"] = AuthorizationRequest(intent=intent).model_dump(mode="json")
    examples["mock_authorization_denied.response.json"] = decision_adapter.dump_python(denied, mode="json")
    return examples


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate offline MOCK examples; never starts an API or executes actions.")
    parser.add_argument("--mock", action="store_true", required=True, help="Explicitly enable offline MOCK fixtures")
    args = parser.parse_args()
    directory = Path(__file__).resolve().parents[2] / "examples"
    directory.mkdir(exist_ok=True)
    for filename, payload in build_mock_examples(mock=args.mock).items():
        (directory / filename).write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
